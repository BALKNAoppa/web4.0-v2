/**
 * `plans.ts`-ээс багц уншина. Багц алга бол ЧИМЭЭГҮЙ алгасахгүй, ШУУД
 * `throw` — id бичихдээ үсэг зөрвөл нүүрэн дээр хагас карт гарахын оронд
 * build унаж, алдаа тэр дороо мэдэгдэнэ.
 */
function uvPlan(id: PlanId): Plan {
  const plan = plans.find((p) => p.id === id);
  if (!plan) throw new Error(`recommended-plans: plans.ts-д "${id}" багц байхгүй`);
  return plan;
}

/** Гурван картад ИЖИЛ тэмдэглэл — нэг л газарт. */
const UV_PRICE_NOTE = "/ сарын суурь хураамж /НӨАТ-гүй үнэ/";

/**
 * Univision-ы НЭГ картыг `plans.ts`-ээс угсарна.
 *
 * ⚠️ ГАРЧИГ нь `plans.ts`-ийн `name` ЯГ ТЭР ЧИГЭЭР ("M+" · "L+" · "XL+").
 *
 * ⚠️ " багц" ГЭСЭН ҮГ ХАСАГДСАН (2026-09-09, захиалагч: "Univision дээр
 * багцын багц гэдэг үгийг хас, 2 мөр болгоод сонин харагдуулж байна").
 * Түр зуур `${plan.name} багц` гэж угсарч байсан — захиалагч эхлээд
 * бичвэрээ ингэж ирүүлсэн. Гэвч гарчиг нь `text-3xl` (30px, extrabold)
 * тул нарийн картад "M+" ба "багц" ХОЁР МӨР болж, үнийн блоктой зэрэгцэх
 * мөр нь доошилдог байв. Мөн section-ийн гарчиг өөрөө "Танд санал болгох
 * БАГЦ" тул үг давхардаж байсан.
 *
 * ⚠️ Тиймээс `truncate`/`text-nowrap` гэх мэт ХАЛТУУР засвар ХИЙГЭЭГҮЙ —
 * шалтгаан нь урт биш, ИЛҮҮДЭЛ үг байсан.
 *
 * ⚠️ `recommended` нь `plans.ts`-ээс ирнэ (L+ дээр `true`) — хоёр файлд
 * "аль нь санал болгох вэ" гэж давхардуулж бичихгүй.
 *
 * ⚠️ `highlights` ОГТ ӨГӨӨГҮЙ. Захиалагчийн ирүүлсэн 3 bullet
 * ("50Mbps интернэт · 80+ ТВ суваг · Суурин утас") нь `groups`-ийн
 * ХУРААНГУЙ хувилбар бөгөөс шинэ загвар нь бүлгүүдийг БҮТНЭЭР харуулдаг
 * тул давхардана. Сувгийн тоо (80+/120+/160+) нь `plans.ts`-ийн IPTV
 * бүлэгт НЭМЭГДСЭН тул мэдээлэл алдагдаагүй.
 */
function uvCard(id: PlanId): PlanCardContent {
  const plan = uvPlan(id);
  return {
    id: `uv-${plan.id}`,
    title: plan.name,
    price: plan.price,
    priceNote: UV_PRICE_NOTE,
    groups: plan.groups,
    recommended: plan.recommended,
    ctaLabel: "Дэлгэрэнгүй харах",
    /**
     * ⚠️ `plan.detailHref` БИШ. Тэр нь `#` (хуучин placeholder) бөгөөс
     * нүүрний контент 2026-09-09-ны шийдвэрээр `/#` хэрэглэдэг. Зам
     * сэргэхэд `plan.detailHref`-ыг дамжуулна.
     */
    href: "/#",
  };
}

