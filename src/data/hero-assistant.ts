// CLARIFY — "хэрэгцээг тодруулж, тохирох шийдлийг олох" ЕРӨНХИЙ ЛОГИК
// =====================================================================
/**
 * ЭНЭ БОЛ ХӨДӨЛГҮҮР (engine), КЕЙС БИШ.
 *
 * Санаа: хэрэглэгчийн ганц өгүүлбэрээс шууд хариу цацахын оронд туслах
 * эхлээд 1-2 БОГИНО тодруулах асуулт тавьж, хэрэгцээг нь ойлгоод дараа нь
 * ЯГ нэг шийдлийг "яагаад" гэсэн үндэслэлтэй нь санал болгоно.
 *
 * Яагаад оноогоор (`favors`), яагаад хатуу дүрмээр биш:
 *   2 алхам × 3 сонголт = 9 хослол. Хослол бүрд гараар хариу бичвэл алхам
 *   нэмэх бүрд ажил үржинэ. Сонголт бүр өөрийн дэмждэг шийдлүүдээ л
 *   зааж өгвөл (`favors`), хосломж автоматаар шийдэгдэнэ — шинэ сонголт
 *   нэмэхэд бусдыг нь хөндөхгүй.
 *
 * КЕЙС НЭМЭХ = зөвхөн энэ файлд `steps` ба `solutions` бичих. `chat-hero.tsx`
 * -ийг хөндөхгүй.
 */

/** Тодруулах асуултын нэг хариулт */
export type ClarifyOption = {
  id: string;
  /** Товч дээр гарах текст — хэрэглэгчийн хэлээр, богино */
  label: string;
  /**
   * Энэ хариулт аль шийдлүүдийг дэмжих вэ (`Solution.id`). Нэг хариулт
   * ХЭД ХЭДЭН шийдлийг дэмжиж болно — эцсийн эрэмбийг нийлбэр оноо шийднэ.
   * Хоосон массив = тухайн хариулт шийдэл сонгоход нөлөөлөхгүй (мэдээлэл
   * цуглуулах зорилготой асуултад хэрэгтэй).
   */
  favors: string[];
  /**
   * Энэ хариулт аль шийдлийг БОЛОМЖГҮЙ болгох вэ (`Solution.id`).
   *
   * `favors`-аас ЯЛГААТАЙ: оноо нэмэхгүй, харин тухайн шийдлийг эрэмбээс
   * БҮРМӨСӨН гаргана. Оноогоор өрсөлдүүлэх нь ХАТУУ шаардлагад БУРУУ:
   * "бусад сүлжээнд ярьдаг" гэсэн хүнд PLUS багц нь тэр эрхийг ОЛГОДОГГҮЙ
   * тул хэдэн оноо цуглуулснаас үл хамааран сонгогдох ёсгүй.
   *
   * ⚠️ БҮХ шийдэл хасагдвал хасалтыг ҮЛ ХЭРЭГСЭНЭ — хоосон хариулт
   * харуулахаас хамгийн тохирохыг харуулах нь дээр.
   */
  excludes?: string[];
};

/** Туслахын тавих нэг тодруулах асуулт */
export type ClarifyStep = {
  id: string;
  /** Туслахын асуух өгүүлбэр */
  prompt: string;
  options: ClarifyOption[];
};

/** Санал болгож болох эцсийн шийдэл */
export type Solution = {
  id: string;
  title: string;
  /** Яагаад энэ шийдэл болох тухай 1 өгүүлбэр */
  description: string;
  /** Картад гарах 2-3 товч онцлог */
  highlights?: string[];
  /**
   * `layout: "plans"` үед — `mobilePlans`-ийн id-ууд. Үнэ, дата зэргийг энд
   * ДАВХАРДУУЛЖ бичихгүй, бодит эх сурвалжаас уншина.
   */
  planIds?: string[];
  /** `layout: "steps"` үед — дугаарлаж харуулах алхмууд */
  steps?: { title: string; hint: string }[];
  /** `layout: "offer"` үед — гарчигтай карт бүлгүүд */
  groups?: OfferGroup[];
  cta?: { label: string; href: string };
};

/**
 * Хэрэгцээ тодруулаад шийдэл санал болгох урсгал.
 *
 * ⚠️ `solutions` нь ДООД ТАЛДАА нэг элементтэй байх ёстой. Хэрэглэгч бүх
 * алхмыг өнгөрөөсний дараа хэн ч оноо аваагүй бол жагсаалтын ЭХНИЙХ нь
 * fallback болно — тиймээс хамгийн ерөнхий шийдлийг эхэнд нь бич.
 */
export type ClarifyResult = {
  kind: "clarify";
  /**
   * Зөвлөмжийг ЯМАР хэлбэрээр задлах вэ. Кейс бүр өөр байх нь зорилготой —
   * бүх persona ижилхэн харагдвал "динамик" мэдрэмж алдагдана.
   *   solution — нэг зөвлөмж карт + онцлохууд
   *   plans    — багцын харьцуулалт (`Solution.planIds`)
   *   steps    — дугаарласан алхмууд (`Solution.steps`)
   *   offer    — гарчигтай карт бүлгүүд (`Solution.groups`)
   */
  layout: "solution" | "plans" | "steps" | "offer";
  /**
   * Шийдлийн ГАРЧГИЙН ӨМНӨ гарах нэг мөр — зөвлөмжийг хэрэглэгчийн
   * хариултуудтай холбоно. Заавал БИШ.
   *
   * ⚠️ Хэрэглэгчийн сонголтыг ИШ ТАТАХГҮЙ (өмнөх "Та «X» гэж хариуллаа"
   * хэлбэр хасагдсан — [[CLARIFY_OUTRO]]-ийн тайлбарыг үз), зөвхөн
   * тооцоолол хийсэн гэдгийг ерөнхийд хэлнэ.
   */
  lead?: string;
  steps: ClarifyStep[];
  solutions: Solution[];
};

/** `resolveClarify`-ийн үр дүн */
export type ClarifyOutcome = {
  /** Хамгийн өндөр оноотой шийдэл */
  best: Solution;
  /**
   * "Яагаад ингэж санал болгов" — хэрэглэгчийн сонгосон, ЭНЭ шийдлийг
   * дэмжсэн хариултуудын шошго. Хоосон бол сонголтууд нь тодорхой заалт
   * өгөөгүй (fallback) гэсэн үг.
   */
  reasons: string[];
  /** Үлдсэн шийдлүүд, оноогоор буурахаар */
  alternatives: Solution[];
  /**
   * Хэрэглэгчийн сонгосон БҮХ хариултын шошго. `reasons`-оос ялгаатай нь:
   * тэр зөвхөн ЯЛАГЧИЙГ дэмжсэнийг агуулдаг бол энэ нь бүгдийг. Ярианы
   * хэлбэрийн хариултад "та юу гэж хэлсэн"-ийг эргүүлж иш татахад.
   */
  picked: string[];
  /** Шийдэл бүрийн цуглуулсан оноо — UI-д харуулахгүй ч дибаг хийхэд */
  scores: Record<string, number>;
};

/**
 * Сонгосон хариултуудаас тохирох шийдлийг гаргана.
 *
 * `answers` — `{ [step.id]: option.id }`. Дутуу бөглөсөн ч ажиллана
 * (бөглөсөн хэсгийн оноогоор), тул алхам дундуур урьдчилан харуулж болно.
 *
 * Тэнцвэл `solutions`-ийн ДАРААЛАЛ шийднэ — жагсаалтын эхнийх хожино.
 * Ингэснээр агуулга бичигч оноо тааруулахгүйгээр давуу эрэмбээ хянана.
 */
export function resolveClarify(
  result: ClarifyResult,
  answers: Record<string, string>,
): ClarifyOutcome {
  const scores: Record<string, number> = {};
  for (const solution of result.solutions) scores[solution.id] = 0;

  const reasonsBySolution: Record<string, string[]> = {};
  const picked: string[] = [];
  /** ХАТУУ хасалт — оноотой өрсөлдөхгүй, эрэмбээс шууд гарна. */
  const excluded = new Set<string>();

  for (const step of result.steps) {
    const pickedId = answers[step.id];
    if (!pickedId) continue;
    const option = step.options.find((o) => o.id === pickedId);
    if (!option) continue;

    picked.push(option.label);

    for (const solutionId of option.excludes ?? []) {
      if (solutionId in scores) excluded.add(solutionId);
    }

    for (const solutionId of option.favors) {
      // Байхгүй шийдлийг зааж бичсэн бол чимээгүй алгасна — агуулгын
      // үсгийн алдаа нь бүх урсгалыг унагаах ёсгүй.
      if (!(solutionId in scores)) continue;
      scores[solutionId] += 1;

      // ⚠️ Оноо нэмэгдэх бүрд шошго нэмэхгүй: ЖИНЛЭСЭН сонголт нь нэг
      // шийдлийг `favors` дотор ХЭД ХЭДЭН УДАА заадаг (тухайн алхмыг
      // хүчтэй болгох арга). Оноо нь давхарлагдах ЁСТОЙ, шошго нь ҮГҮЙ.
      const reasons = (reasonsBySolution[solutionId] ??= []);
      if (!reasons.includes(option.label)) reasons.push(option.label);
    }
  }

  // ⚠️ Хасалтыг ОНООНООС ӨМНӨ хэрэглэнэ. Бүгд хасагдвал үл хэрэгсэнэ —
  // хоосон хариулт харуулахаас хамгийн тохирохыг харуулах нь дээр.
  const allowed = result.solutions.filter((solution) => !excluded.has(solution.id));
  const pool = allowed.length > 0 ? allowed : result.solutions;

  // Тогтвортой эрэмбэ: оноо буурахаар, тэнцвэл анхны дараалал хэвээр.
  const ranked = pool
    .map((solution, index) => ({ solution, index, score: scores[solution.id] }))
    .sort((a, b) => b.score - a.score || a.index - b.index)
    .map((entry) => entry.solution);

  const best = ranked[0];

  return {
    best,
    reasons: reasonsBySolution[best.id] ?? [],
    alternatives: ranked.slice(1),
    picked,
    scores,
  };
}

